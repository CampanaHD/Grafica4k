import test from 'node:test';
import assert from 'node:assert/strict';
import express from 'express';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {createAuthSystem,hashPassword} from '../server/auth';
import {createTeamOperations} from '../server/teamOperations';
import {createQuotationsRouter} from '../server/quotationsApi';
import {formatQuotationMessage} from '../src/utils/quotationMessage';
import {outsourcedChargedValue} from '../src/utils/outsourcing';

test('single outsourced value, optional PIN and module permissions persist and protect production edits',async()=>{
  const dir=mkdtempSync(path.join(tmpdir(),'nagano-pin-modules-'));
  const initial={email:'qa@teste.local',...hashPassword('Somente-no-teste!')};
  const auth=createAuthSystem(dir,initial),app=express();app.use(express.json());app.use(auth.router);
  app.use('/api',(req,res,next)=>auth.requireLogin(req,res,()=>auth.requireProfile(req,res,next)));
  let ops:ReturnType<typeof createTeamOperations>;
  const quotes=createQuotationsRouter(()=>undefined,dir,()=>undefined,undefined,{getThirdParty:id=>ops.getThirdParty(id),onSaved:(q,a)=>ops.quotationSaved(q,a)});
  ops=createTeamOperations(auth.activity,quotes.get,dir);app.use(ops.router);app.use(quotes.router);
  const server=app.listen(0);await new Promise<void>(resolve=>server.once('listening',resolve));
  const base=`http://127.0.0.1:${(server.address() as any).port}`;let cookie='',profile='';
  const call=async(url:string,method='GET',body?:unknown)=>{
    const response=await fetch(base+url,{method,headers:{Cookie:cookie,...(profile&&!url.startsWith('/api/auth')?{'X-Nagano-Profile':profile}:{}),...(body===undefined?{}:{'Content-Type':'application/json'})},body:body===undefined?undefined:JSON.stringify(body)});
    if(response.headers.get('set-cookie'))cookie=response.headers.get('set-cookie')!.split(';')[0];
    const data=await response.json();if(response.ok&&url==='/api/auth/profile')profile=data.profile.id;
    return {status:response.status,data};
  };
  try{
    await call('/api/auth/login','POST',{email:initial.email,password:'Somente-no-teste!'});
    await call('/api/auth/profile','POST',{profileId:'administrator'});
    const design={id:'arte',name:'Arte',role:'DESIGN',color:'#3158ed',active:true,modules:['dashboard','work_orders','kanban','activity']};
    let saved=await call('/api/team/profiles/arte','PUT',design);assert.equal(saved.status,200);assert.equal(saved.data.data.hasPin,false);
    assert.equal((await call('/api/team/profiles/arte','PUT',{...design,modules:['inexistente']})).status,400);
    assert.equal((await call('/api/team/profiles/arte','PUT',{...design,modules:[]})).status,400);
    assert.equal((await call('/api/team/profiles/arte','PUT',{...design,pin:'12'})).status,400);
    assert.equal((await call('/api/auth/profile','POST',{profileId:'arte'})).status,200);
    assert.equal((await call('/api/quotations')).status,403);
    assert.equal((await call('/api/third-parties')).status,403);
    assert.equal((await call('/api/materials')).status,403);
    assert.equal((await call('/api/work-orders/bootstrap','POST',{orders:[]})).status,403);
    await call('/api/auth/profile','POST',{profileId:'administrator'});
    saved=await call('/api/team/profiles/arte','PUT',{...design,pin:'5826'});assert.equal(saved.data.data.hasPin,true);
    assert.doesNotMatch(JSON.stringify((await call('/api/auth/session')).data),/5826|salt|hash|"pin":/i);
    assert.equal((await call('/api/auth/profile','POST',{profileId:'arte'})).status,403);
    assert.equal((await call('/api/auth/profile','POST',{profileId:'arte',pin:'0000'})).status,403);
    assert.equal((await call('/api/auth/session')).data.profile.id,'administrator');
    await call('/api/third-parties/prestador','PUT',{name:'Parceiro',services:['Adesivação','Retirada de adesivos'],pixKey:'CHAVE-INTERNA',active:true});
    const row={id:'servico',thirdPartyId:'prestador',thirdPartyName:'forjado',services:['Adesivação','Retirada de adesivos'],value:275};
    const qInput:any={id:'simples',customerId:'cliente',customerName:'Cliente',status:'ORCAMENTO',items:[],outsourcedServices:[row]};
    let q=(await call('/api/quotations/simples','PUT',qInput)).data.data;
    assert.equal(q.totalAmount,275);assert.equal(q.outsourcedServices[0].thirdPartyName,'Parceiro');
    assert.equal(q.outsourcedServices[0].quantity,undefined);assert.equal(q.outsourcedServices[0].cost,undefined);assert.equal(q.outsourcedServices[0].salePrice,undefined);
    const message=formatQuotationMessage(q);assert.match(message,/Adesivação/);assert.match(message,/Retirada de adesivos/);assert.match(message,/275,00/);assert.doesNotMatch(message,/CHAVE-INTERNA/);
    assert.equal((await call('/api/quotations/invalid','PUT',{...qInput,id:'invalid',outsourcedServices:[{...row,services:[]}]})).status,400);
    assert.equal((await call('/api/quotations/invalid','PUT',{...qInput,id:'invalid',outsourcedServices:[{...row,services:['Não cadastrado']}]})).status,400);
    assert.equal((await call('/api/quotations/invalid','PUT',{...qInput,id:'invalid',outsourcedServices:[{...row,value:-5}]})).status,400);
    let history=(await call('/api/third-parties/prestador/history')).data.data;assert.equal(history.length,1);assert.deepEqual(history[0].services,row.services);assert.equal(outsourcedChargedValue(history[0]),275);
    q=(await call('/api/quotations/simples','PUT',{...q,outsourcedServices:[{...row,services:['Adesivação'],value:310}]})).data.data;
    history=(await call('/api/third-parties/prestador/history')).data.data;assert.equal(history.length,1);assert.equal(history[0].value,310);
    q=(await call('/api/quotations/simples/approve','POST',{revision:q.revision,workOrderId:'os'})).data.data;
    let order=(await call('/api/work-orders/os','PUT',{id:'os',quotationId:q.id,productionStatus:'PRODUCAO_ARTES',amountPaid:50,serviceName:'Adesivação'})).data.data;
    assert.equal(order.remainingBalance,260);
    assert.equal((await call('/api/auth/profile','POST',{profileId:'arte',pin:'5826'})).status,200);
    let technical=(await call('/api/work-orders')).data.data[0];
    for(const key of ['totalAmount','amountPaid','remainingBalance','paymentMethod'])assert.equal(technical[key],undefined);
    assert.equal(technical.outsourcedServices[0].value,undefined);
    const changed=await call('/api/work-orders/os','PUT',{...technical,productionStatus:'ARTE_APROVADA',productionNotes:'Conferir recorte.'});
    assert.equal(changed.status,200);assert.equal(changed.data.data.updatedBy.name,'Arte');assert.equal(changed.data.data.totalAmount,undefined);
    assert.equal((await call('/api/work-orders/os','PUT',{...changed.data.data,amountPaid:0})).status,403);
    assert.equal((await call('/api/team/profiles/arte','PUT',{...design,modules:['finance']})).status,403);
    await call('/api/auth/profile','POST',{profileId:'administrator'});
    order=(await call('/api/work-orders')).data.data[0];assert.equal(order.totalAmount,310);assert.equal(order.amountPaid,50);assert.equal(order.remainingBalance,260);assert.equal(order.productionNotes,'Conferir recorte.');
    const retained=await call('/api/team/profiles/arte','PUT',{...design,pin:''});assert.equal(retained.data.data.hasPin,true);
    assert.equal((await call('/api/auth/profile','POST',{profileId:'arte',pin:'5826'})).status,200);
    await call('/api/auth/profile','POST',{profileId:'administrator'});
    await call('/api/team/profiles/arte','PUT',{...design,removePin:true});
    assert.equal((await call('/api/auth/profile','POST',{profileId:'arte'})).status,200);
    await call('/api/auth/profile','POST',{profileId:'administrator'});
    await call('/api/team/profiles/arte','PUT',{...design,pin:'5826'});
    for(let i=0;i<8;i++)assert.equal((await call('/api/auth/profile','POST',{profileId:'arte',pin:'0000'})).status,403);
    assert.equal((await call('/api/auth/profile','POST',{profileId:'arte',pin:'5826'})).status,429);
    assert.equal((await call('/api/auth/session')).data.profile.id,'administrator');
  }finally{await new Promise<void>(resolve=>server.close(()=>resolve()));quotes.close();ops.close();auth.close();const resolved=path.resolve(dir);assert.ok(resolved.startsWith(path.resolve(tmpdir())+path.sep));rmSync(resolved,{recursive:true,force:true});}
});

